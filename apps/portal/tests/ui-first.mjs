
import {chromium} from 'playwright'
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'
const accounts=JSON.parse(readFileSync('/var/lib/vibe-os/portal-private/student-logins.json'))
const out='/opt/vibe-os/platform/evidence/portal-ui'
mkdirSync(out,{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1})
process.on('uncaughtException',async e=>{console.error(e.message);await browser.close();process.exit(1)})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('401'))errors.push(m.text())})
await page.goto('https://80.249.145.94/',{waitUntil:'networkidle'})
await page.screenshot({path:out+'/login.png',fullPage:true})
await page.getByLabel('Логин',{exact:true}).fill(accounts[0].login)
await page.getByLabel('Пароль',{exact:true}).fill(accounts[0].password)
await page.getByRole('button',{name:'Войти в пространство'}).click()
await page.getByRole('heading',{name:'Vibe-coding by Eduson Kids'}).waitFor()
await page.waitForLoadState('networkidle')
await page.screenshot({path:out+'/dashboard.png',fullPage:true})
console.log('Dashboard loaded over trusted HTTPS.')
await page.getByRole('button',{name:'Открыть Моя первая идея'}).click()
await page.locator('.cm-editor').waitFor()
await page.screenshot({path:out+'/workspace.png',fullPage:true})
await page.getByRole('button',{name:'Просмотр',exact:true}).click()
await page.locator('iframe[title="Предпросмотр проекта"]').waitFor()
await page.frameLocator('iframe').getByRole('heading',{name:'Большие идеи начинаются с малого.'}).waitFor()
await page.frameLocator('iframe').getByRole('button',{name:'Добавить немного вдохновения'}).click()
await page.frameLocator('iframe').getByText('Создай сайт о том, что любишь.').waitFor()
await page.screenshot({path:out+'/preview.png',fullPage:true})
console.log('Isolated interactive project preview passed.')
await page.getByRole('button',{name:'Хостинг',exact:true}).click()
await page.getByRole('heading',{name:'Пусть проекты живут'}).waitFor()
await page.screenshot({path:out+'/hosting.png',fullPage:true})
await page.locator('.sidebar nav button').filter({hasText:'Проекты'}).click()
await page.getByRole('button',{name:'Открыть Первые шаги в Python'}).click()
await page.locator('.cm-editor').waitFor()
await page.getByRole('button',{name:'Запустить',exact:true}).click()
await page.locator('.console-panel pre').filter({hasText:'Привет, исследователь!'}).waitFor({timeout:15000})
if(!await page.locator('.console-panel pre').textContent().then(v=>v.includes('код 0')))throw new Error('Python command did not exit successfully')
await page.screenshot({path:out+'/python.png',fullPage:true})
console.log('Python execution passed from student UI.')
await page.getByRole('button',{name:'Обзор',exact:true}).click()
await page.setViewportSize({width:390,height:844})
await page.screenshot({path:out+'/mobile-dashboard.png',fullPage:true})
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1)
if(overflow)throw new Error('Mobile horizontal overflow')
await context.close();await browser.close()
writeFileSync('/opt/vibe-os/platform/evidence/portal-ui-first.json',JSON.stringify({passed:true,errors,checks:['trusted-ip-https','login','dashboard','code-editor','opaque-preview','preview-script','hosting','python-run','mobile-layout'],screenshots:out},null,2)+'\n')
if(errors.length)throw new Error('Browser errors: '+errors.join(';'))
console.log('UI checks passed without model requests.')
